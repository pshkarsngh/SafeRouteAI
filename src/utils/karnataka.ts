import type { Place } from './places'

interface Town {
  name: string
  lng: number
  lat: number
}

const district = (name: string, towns: Town[]): Place[] =>
  towns.map(({ name: town, lng, lat }, index) => ({
    id: `${name}-${town}`.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    name: town,
    region: 'Karnataka, India',
    lngLat: [lng, lat],
    zoom: index === 0 ? 12 : 11,
    tags: ['karnataka', name.toLowerCase().replace(/\s+/g, '-')],
  }))

